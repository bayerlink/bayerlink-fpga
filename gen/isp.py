"""Generate the demo ISP: a revela pipeline, in fabric, in colour.

blacklevel -> whitebalance -> bilinear demosaic -> rgb_gamma, composed
by revela and generated through np2hw -- the same flow `revela run
--rtl` verifies against the NumPy model. The Verilog is NEVER
committed; regenerate, don't edit.

Parameters are BAKED as constants in a wrapper for this first fabric
ISP (the register/DDC path is designed, not yet built): the OV5647
pedestal, a plain indoor white balance, a 2.2 tone curve. The wrapper
is the only hand-shaped text, and it is generated too.

    pip install revela   (or the sibling checkout)
    python3 gen/isp.py --width 512 --height 240
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent

PEDESTAL = 16          # OV5647, 10-bit scale; measured 15 in the dark
# MEASURED here, from the slope of a ColorChecker's neutral ramp in this
# garden's light. White balance and the colour matrix do DIFFERENT jobs:
# the gains adapt to the ILLUMINANT (what an AWB loop would be doing
# continuously), the matrix corrects the SENSOR's filters and is fixed.
# The matrix assumes neutrals arrive already balanced -- its rows sum to
# 256, so it preserves whatever cast reaches it rather than removing one.
# The published generic gains under-corrected and left the picture green.
# Fitted from the RAMP, not one grey patch, because red carries an offset
# that does not scale with the light: IR past a weak cut filter.
WB = {"r": 491, "gr": 256, "gb": 256, "b": 305}   # Q8.8, this light
GAMMA = 2.2
# Identity in Q.8: the matrix is WIRED but not yet CHOSEN. The daylight
# set belongs with the pedestal and the white balance -- one coherent
# change, judged on a screen -- not slipped in beside a structural one.
# The PUBLISHED 5890 K calibration for this sensor, not the one this
# bench fitted. Ours came out with a 2.46x red diagonal because the
# chart was measured through 9% veiling glare, and on real foliage --
# which is violently IR-bright, and this module's IR-cut filter is weak
# -- that turned every leaf red. A lab calibration beats a contaminated
# one, and the failure mode is not visible on a chart.
CCM = [[547, -167, -124], [-124, 494, -115], [-34, -140, 431]]


def _emit_control_wrapper(a, args) -> None:
    """The wrapper when parameters are LIVE.

    Shorter than the baked one, because there is nothing to bake: the
    generated control wrapper already holds the datapath and the register
    file, and commits writes at a frame boundary on its own. All this
    adds is the header latch -- the same pend/active pattern the baked
    wrapper uses -- and the AXI4-Lite port carried out to the boundary.
    """
    a("// generated by gen/isp.py -- AXI4-Lite wrapper around the revela")
    a("// pipeline. Parameters are LIVE: written over the register map,")
    a("// landing in a shadow, committed at the frame boundary, so a")
    a("// frame is processed with one coherent set or none of it.")
    a("module revela_isp (")
    a("    input  wire        clk,")
    a("    input  wire        rst,")
    a("    // The header's facts, straight from the receiver. NOT the")
    a("    // depth: the receiver has already aligned samples to this")
    a("    // build's, so hdr_bits is carried for software only.")
    a("    input  wire [15:0] hdr_width,")
    a("    input  wire [15:0] hdr_height,")
    a("    input  wire [1:0]  hdr_phase,")
    a("    input  wire [4:0]  hdr_bits,")
    a("    // Every coefficient, and every identity word, behind this")
    a("    // port. The interface is DECLARED, not left to be inferred")
    a("    // from port names: an inferred one is a guess, and a guess")
    a("    // about an AXI interface cost a day on 2026-08-17.")
    a("    //")
    a("    // ON ITS OWN CLOCK. `clk` above is recovered from the HDMI")
    a("    // link, so it STOPS whenever the link is down -- including")
    a("    // just after this bitstream is loaded. AXI has no timeout, so")
    a("    // a slave with no clock never answers and the processor waits")
    a("    // for it forever. That hung this board on 2026-08-17 and")
    a("    // needed the power pulled. The association below is what")
    a("    // tells the block design which clock this port runs on, and")
    a("    // naming the wrong one is exactly how it ended up on a clock")
    a("    // that can stop.")
    a('    (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF s_axi, '
      'ASSOCIATED_RESET s_axi_aresetn" *)')
    a('    (* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 '
      's_axi_aclk CLK" *)')
    a("    input  wire        s_axi_aclk,")
    a('    (* X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW" *)')
    a('    (* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 '
      's_axi_aresetn RST" *)')
    a("    input  wire        s_axi_aresetn,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi AWADDR" *)')
    a("    input  wire [14:0] s_axi_awaddr,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi AWVALID" *)')
    a("    input  wire        s_axi_awvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi AWREADY" *)')
    a("    output wire        s_axi_awready,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi WDATA" *)')
    a("    input  wire [31:0] s_axi_wdata,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi WSTRB" *)')
    a("    input  wire [3:0] s_axi_wstrb,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi WVALID" *)')
    a("    input  wire        s_axi_wvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi WREADY" *)')
    a("    output wire        s_axi_wready,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi BRESP" *)')
    a("    output wire [1:0] s_axi_bresp,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi BVALID" *)')
    a("    output wire        s_axi_bvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi BREADY" *)')
    a("    input  wire        s_axi_bready,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi ARADDR" *)')
    a("    input  wire [14:0] s_axi_araddr,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi ARVALID" *)')
    a("    input  wire        s_axi_arvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi ARREADY" *)')
    a("    output wire        s_axi_arready,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi RDATA" *)')
    a("    output wire [31:0] s_axi_rdata,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi RRESP" *)')
    a("    output wire [1:0] s_axi_rresp,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi RVALID" *)')
    a("    output wire        s_axi_rvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 s_axi RREADY" *)')
    a("    input  wire        s_axi_rready,")
    a("    input  wire        in_valid,")
    a("    output wire        in_ready,")
    a(f"    input  wire [{args.bits - 1}:0] in_data,")
    a("    input  wire        in_sof,")
    a("    input  wire        in_eol,")
    a("    input  wire        in_last,")
    a("    output wire        out_valid,")
    a("    input  wire        out_ready,")
    a("    output wire [29:0] out_data,")
    a("    output wire        out_sof,")
    a("    output wire        out_eol,")
    a("    output wire        out_last")
    a(");")
    a(f"    reg [15:0] ctx_w = 16'd{args.width};")
    a(f"    reg [15:0] ctx_h = 16'd{args.height};")
    a("    reg [1:0]  ctx_ph = 2'd2;")
    a(f"    reg [4:0]  ctx_bd = 5'd{args.bits};")
    a("    always @(posedge clk)")
    a("        if (in_valid && in_ready && in_sof) begin")
    a("            ctx_w  <= hdr_width;")
    a("            ctx_h  <= hdr_height;")
    a("            ctx_ph <= hdr_phase;")
    a("            ctx_bd <= hdr_bits;")
    a("        end")
    a("    revela_isp_core_ctrl core (")
    a("        .clk(clk), .rst(rst),")
    a("        .s_axil_aclk(s_axi_aclk), .s_axil_aresetn(s_axi_aresetn),")
    a("        .s_axil_awaddr(s_axi_awaddr), .s_axil_awvalid(s_axi_awvalid),")
    a("        .s_axil_awready(s_axi_awready),")
    a("        .s_axil_wdata(s_axi_wdata), .s_axil_wstrb(s_axi_wstrb),")
    a("        .s_axil_wvalid(s_axi_wvalid), .s_axil_wready(s_axi_wready),")
    a("        .s_axil_bresp(s_axi_bresp), .s_axil_bvalid(s_axi_bvalid),")
    a("        .s_axil_bready(s_axi_bready),")
    a("        .s_axil_araddr(s_axi_araddr), .s_axil_arvalid(s_axi_arvalid),")
    a("        .s_axil_arready(s_axi_arready),")
    a("        .s_axil_rdata(s_axi_rdata), .s_axil_rresp(s_axi_rresp),")
    a("        .s_axil_rvalid(s_axi_rvalid), .s_axil_rready(s_axi_rready),")
    a("        .ctx_width(ctx_w), .ctx_height(ctx_h),")
    a("        .ctx_bayer_phase(ctx_ph), .ctx_bit_depth(ctx_bd),")
    a("        .isp_in_valid(in_valid), .isp_in_ready(in_ready),")
    a("        .isp_in_data(in_data),")
    a("        .isp_in_sof(in_sof), .isp_in_eol(in_eol), .isp_in_last(in_last),")
    a("        .isp_out_valid(out_valid), .isp_out_ready(out_ready),")
    a("        .isp_out_data(out_data),")
    a("        .isp_out_sof(out_sof), .isp_out_eol(out_eol),")
    a("        .isp_out_last(out_last)")
    a("    );")
    a("endmodule")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--width", type=int, default=512)
    parser.add_argument("--height", type=int, default=240)
    parser.add_argument("--bits", type=int, default=10)
    # BAKED or LIVE. Baked is the demo that works: constants in the
    # wrapper, nothing to write, nothing to get wrong. Live emits the
    # AXI4-Lite register file np2hw generates, whose writes land in a
    # shadow and commit at a frame boundary -- so a frame is processed
    # with one coherent set of coefficients rather than half of two.
    # The default is the one that has a picture behind it.
    parser.add_argument("--control", action="store_true",
                        help="parameters from registers instead of baked "
                             "constants")
    parser.add_argument("--clock-mhz", type=float, default=148.5,
                        help="the ISP's clock: the receiver's pixel "
                             "clock, constrained at the fastest legal "
                             "link. Every pointwise stage is depth-"
                             "checked against it at generation time; a "
                             "too-deep stage is CUT into pipeline "
                             "stages there, by arithmetic on the "
                             "traced expression graph")
    args = parser.parse_args()

    from revela.blocks import registry
    from revela.compose import Pipeline
    from revela.host.curves import knots_from_curve
    from revela.stream import StreamSpec

    reg = registry()
    # Geometry and CFA phase arrive in the STREAM's header, so with a
    # control plane they stay PORTS rather than becoming registers: a
    # register holding a second copy of a header fact could be set to
    # disagree with the picture arriving. The crop window stays a
    # register, because where to crop is genuinely software's choice.
    from_stream = (("width", "height", "bayer_phase", "bit_depth")
                   if args.control else ())
    p = Pipeline("revela_isp_core",
                 StreamSpec(bit_depth=args.bits, channels=1),
                 args.width, args.height,
                 inputs=("isp_in",), outputs=("isp_out",),
                 context_from_stream=from_stream)
    chain = [("bl", "blacklevel", None),
             ("wb", "whitebalance", None),
             ("hg", "ha_green", None),
             ("hr", "ha_rb", None),
             ("cc", "ccm", None),
             ("gm", "rgb_gamma", {"knots": {"bits": args.bits + 1}}),
             ("lg", "logo", None)]
    for name, kind, regs in chain:
        p.add(name, reg[kind], registers=regs)
    src = "isp_in"
    for name, kind, _ in chain:
        block = reg[kind]
        p.connect(src, f"{name}.{block.ports.inputs[0]}")
        src = f"{name}.{block.ports.outputs[0]}"
    p.connect(src, "isp_out")
    generated = p.generate(control=args.control,
                           clk_ns=1000.0 / args.clock_mhz)
    print(f"timing: every pointwise stage fits "
          f"{1000.0 / args.clock_mhz:.1f} ns ({args.clock_mhz:g} MHz), "
          "by the traced depth model")

    # Generation and verification are ONE step: the same composition
    # runs under Verilator against the same NumPy models with the same
    # baked values, on a synthetic colour scene. An unverified pipeline
    # cannot reach a bitstream from here.
    import numpy as np
    from revela import run as runner
    values = {
        "hg": {},
        "hr": {},
        "cc": {f"m_{r}_{c}": CCM[r][c] for r in range(3) for c in range(3)},
        "lg": {},
        "bl": {f"offset_{pos}": -PEDESTAL
               for pos in ("0_0", "0_1", "1_0", "1_1")},
        "wb": {"gain_0_0": WB["r"], "gain_0_1": WB["gr"],
               "gain_1_0": WB["gb"], "gain_1_1": WB["b"]},
        "gm": {f"knots_{i}": int(k) for i, k in enumerate(
            knots_from_curve(lambda v: v ** (1.0 / GAMMA),
                             count=33, bit_depth=args.bits))},
    }
    context = {"bayer_phase": 2}
    rng = np.random.default_rng(20260813)
    frame = rng.integers(0, 1 << args.bits,
                         size=(args.height, args.width), dtype=np.uint16)
    chain = runner.pixel_chain(p, None, None)
    model = runner.run_model(chain, frame, values, context, args.bits)
    rtl = runner.run_rtl(chain, frame, values, context, args.bits)
    if not np.array_equal(model, rtl):
        raise SystemExit("the generated RTL DIFFERS from the model; "
                         "refusing to emit an unverified pipeline")
    print(f"twin: bit-exact with the model ({model.size} words)")

    knots = knots_from_curve(lambda v: v ** (1.0 / GAMMA),
                             count=33, bit_depth=args.bits)
    kw = args.bits + 1

    L = []
    a = L.append
    if args.control:
        _emit_control_wrapper(a, args)
        out = HERE / "hdl" / "generated"
        out.mkdir(exist_ok=True)
        text = "\n".join(t for _, t in generated.modules)
        (out / "revela_isp.v").write_text(text + "\n\n" + "\n".join(L) + "\n")
        (out / "revela_isp.regmap.json").write_text(
            json.dumps(p.register_map(), indent=2) + "\n")
        print(f"generated hdl/generated/revela_isp.v "
              f"({args.width}x{args.height}@{args.bits}b, "
              f"{len(generated.modules)} modules + AXI4-Lite wrapper); "
              "parameters are LIVE, written over the register map")
        return
    a("// generated by gen/isp.py -- constants wrapper around the revela")
    a("// pipeline core. Parameters are BAKED for the demo: pedestal "
      f"{PEDESTAL},")
    a(f"// WB Q8.8 {tuple(WB.values())}, CCM Q.8 {CCM}, "
      f"gamma {GAMMA} in 33 knots.")
    a("module revela_isp (")
    a("    input  wire        clk,")
    a("    input  wire        rst,")
    a("    // The header's facts, straight from the receiver: the stream")
    a("    // owns its geometry and phase; the build owns only maximums.")
    a("    // NOT the depth: the receiver has already aligned samples to")
    a("    // this build's, so hdr_bits is carried for software and no")
    a("    // longer describes what arrives on in_data.")
    a("    // Latched as each frame's SOF enters, so a change lands on a")
    a("    // frame boundary -- the pend/active pattern, third outing.")
    a("    input  wire [15:0] hdr_width,")
    a("    input  wire [15:0] hdr_height,")
    a("    input  wire [1:0]  hdr_phase,")
    a("    input  wire [4:0]  hdr_bits,")
    a("    input  wire        in_valid,")
    a("    output wire        in_ready,")
    a(f"    input  wire [{args.bits - 1}:0] in_data,   // the receiver's "
      "sample, already aligned to this depth")
    a("    input  wire        in_sof,")
    a("    input  wire        in_eol,")
    a("    input  wire        in_last,")
    a("    output wire        out_valid,")
    a("    input  wire        out_ready,")
    a("    output wire [29:0] out_data,  // R low, G mid, B high, 10b each")
    a("    output wire        out_sof,")
    a("    output wire        out_eol,")
    a("    output wire        out_last")
    a(");")
    a(f"    reg [15:0] ctx_w = 16'd{args.width};")
    a(f"    reg [15:0] ctx_h = 16'd{args.height};")
    a("    reg [1:0]  ctx_ph = 2'd2;")
    a(f"    reg [4:0]  ctx_bd = 5'd{args.bits};")
    a("    always @(posedge clk)")
    a("        if (in_valid && in_ready && in_sof) begin")
    a("            ctx_w  <= hdr_width;")
    a("            ctx_h  <= hdr_height;")
    a("            ctx_ph <= hdr_phase;")
    a("            ctx_bd <= hdr_bits;")
    a("        end")
    a("    revela_isp_core core (")
    a("        .clk(clk), .rst(rst),")
    a("        .ctx_width(ctx_w),")
    a("        .ctx_height(ctx_h),")
    a("        .ctx_window_x0(16'd0), .ctx_window_y0(16'd0),")
    a("        .ctx_window_x1(ctx_w), .ctx_window_y1(ctx_h),")
    a("        .ctx_bayer_phase(ctx_ph),")
    a("        .ctx_bit_depth(ctx_bd),")
    for pos, colour in (("0_0", "r"), ("0_1", "gr"), ("1_0", "gb"),
                        ("1_1", "b")):
        a(f"        .param_bl_offset_{pos}(-16'sd{PEDESTAL}),")
        a(f"        .param_wb_gain_{pos}(16'd{WB[colour]}),")
    for r in range(3):
        for c in range(3):
            v = CCM[r][c]
            sign = "-" if v < 0 else ""
            a(f"        .param_cc_m_{r}_{c}({sign}16'sd{abs(v)}),")
    for i, k in enumerate(knots):
        a(f"        .param_gm_knots_{i}({kw}'d{int(k)}),")
    a(f"        .isp_in_valid(in_valid), .isp_in_ready(in_ready),")
    a("        .isp_in_data(in_data),")
    a("        .isp_in_sof(in_sof), .isp_in_eol(in_eol), "
      ".isp_in_last(in_last),")
    a("        .isp_out_valid(out_valid), .isp_out_ready(out_ready),")
    a("        .isp_out_data(out_data),")
    a("        .isp_out_sof(out_sof), .isp_out_eol(out_eol), "
      ".isp_out_last(out_last)")
    a("    );")
    a("endmodule")

    out = HERE / "hdl" / "generated"
    out.mkdir(exist_ok=True)
    text = "\n".join(t for _, t in generated.modules)
    (out / "revela_isp.v").write_text(text + "\n\n" + "\n".join(L) + "\n")
    print(f"generated hdl/generated/revela_isp.v "
          f"({args.width}x{args.height}@{args.bits}b, "
          f"{len(generated.modules)} core modules + constants wrapper)")


if __name__ == "__main__":
    main()
