"""Generate the display raster: np2hw's scanout, plus a constants wrapper.

The raster stops being hand-written Verilog. np2hw emits it from the
mode table -- the one owner of what a 1080p60 raster is -- and the
claims that come with it are the laws this bench paid for: a frame may
be dropped, never displaced; a window that does not fit is refused, not
clipped; pixel and enable leave together.

Placement is a run-time fact and arrives on registers. This build bakes
it in a wrapper, exactly as gen/isp.py bakes the ISP's parameters,
because the register file is designed and not yet built. When it lands,
the wrapper is deleted rather than rewritten.

    python3 gen/scanout.py --mode 1080p60 --window 1920x1080
"""
import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", default="1080p60",
                        help="a name from np2hw's raster table")
    parser.add_argument("--window", default="",
                        help="WxH of the picture in the framebuffer "
                             "(default: the mode's full active area)")
    parser.add_argument("--at", default="",
                        help="X,Y placement; omit to centre the window")
    args = parser.parse_args()

    from np2hw.video_out import mode_timing, scanout

    timing = mode_timing(args.mode)
    if args.window:
        w, _, h = args.window.partition("x")
        win_w, win_h = int(w), int(h)
    else:
        win_w, win_h = timing["h_active"], timing["v_active"]
    centre = not args.at
    x0, y0 = (0, 0)
    if args.at:
        sx, _, sy = args.at.partition(",")
        x0, y0 = int(sx), int(sy)

    core = scanout(mode=args.mode, module_name="scanout", sink="dvi",
                   data_bits=24, fill=0x101010)

    L = []
    a = L.append
    a("// generated by gen/scanout.py -- np2hw's scanout with this")
    a("// build's placement baked. Placement is a RUN-TIME fact; it is")
    a("// constant here only because the register file is not built yet,")
    a("// and this wrapper is deleted when it is.")
    a("module scanout_top (")
    a("    input  wire        clk,")
    a("    input  wire        rst,")
    a("    input  wire        locked,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 s_axis TDATA" *)')
    a("    input  wire [23:0] s_axis_tdata,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 s_axis TVALID" *)')
    a("    input  wire        s_axis_tvalid,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 s_axis TREADY" *)')
    a("    output wire        s_axis_tready,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 s_axis TUSER" *)')
    a("    input  wire        s_axis_tuser,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:axis:1.0 s_axis TLAST" *)')
    a("    input  wire        s_axis_tlast,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:vid_io:1.0 vid_io ACTIVE_VIDEO" *)')
    a("    output wire        vid_active_video,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:vid_io:1.0 vid_io DATA" *)')
    a("    output wire [23:0] vid_data,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:vid_io:1.0 vid_io HSYNC" *)')
    a("    output wire        vid_hsync,")
    a('    (* X_INTERFACE_INFO = "xilinx.com:interface:vid_io:1.0 vid_io VSYNC" *)')
    a("    output wire        vid_vsync,")
    a("    output wire [14:0] status")
    a(");")
    a("    wire [15:0] full_status;")
    a("    wire [15:0] act_x0, act_y0;")
    a("    scanout core (")
    a("        .clk(clk), .rst(rst), .locked(locked),")
    a("        .s_axis_tdata(s_axis_tdata), .s_axis_tvalid(s_axis_tvalid),")
    a("        .s_axis_tready(s_axis_tready), .s_axis_tuser(s_axis_tuser),")
    a("        .s_axis_tlast(s_axis_tlast),")
    a(f"        .param_win_x0(16'd{x0}), .param_win_y0(16'd{y0}),")
    a(f"        .param_win_w(16'd{win_w}), .param_win_h(16'd{win_h}),")
    a(f"        .param_center(1'b{int(centre)}),")
    a("        .act_x0(act_x0), .act_y0(act_y0),")
    a("        .vid_active_video(vid_active_video), .vid_data(vid_data),")
    a("        .vid_hsync(vid_hsync), .vid_vsync(vid_vsync),")
    a("        .status(full_status));")
    a("    // The board's status word is 15 bits wide; drop the top bit,")
    a("    // which is the spare of the vsync counter.")
    a("    assign status = full_status[14:0];")
    a("endmodule")

    out = HERE / "hdl" / "generated"
    out.mkdir(exist_ok=True)
    (out / "scanout.v").write_text(core["verilog"] + "\n".join(L) + "\n")
    print(f"generated hdl/generated/scanout.v -- {timing['name']}, "
          f"{timing['pixel_mhz']:g} MHz, window {win_w}x{win_h} "
          + (f"centred" if centre else f"at {x0},{y0}"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
