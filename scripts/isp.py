"""The fabric ISP demo: camera to colour, no ARM in the datapath.

blacklevel -> whitebalance -> bilinear demosaic -> rgb_gamma, all
generated by revela/np2hw and running in fabric between the bayerlink
receiver and the framebuffer. The ARM's whole job is this script:
point two VDMA channels at one buffer, flip the mode bit, report.

    python3 isp.py --bit rx.bit
"""
import argparse
import signal
import sys
import time

from pynq import Overlay, allocate, MMIO

MODE_W, MODE_H = 1920, 1080
ISP_W, ISP_H = 1920, 1080   # the TV's best defines the sensor's ask


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bit", default="rx.bit")
    parser.add_argument("--skew", type=int, default=352,
                        help="pixels to advance the scanout read by, to "
                             "cancel the read engine's own marker-to-data "
                             "lag. MEASURED per bitstream with scripts/"
                             "ruler.py and a capture card; must stay a "
                             "multiple of 16 (64-byte aligned)")
    parser.add_argument("--seconds", type=float, default=0.0,
                        help="status loop duration; 0 = forever")
    args = parser.parse_args()

    # A plain kill (SIGTERM) must end the loop cleanly: the fabric keeps
    # the picture, and nothing is left needing kill -9.
    signal.signal(signal.SIGTERM, lambda *_: sys.exit(0))

    overlay = Overlay(args.bit, download=True)
    ctrl = MMIO(overlay.ip_dict["ctrl_gpio"]["phys_addr"], 0x1000)
    gpio = MMIO(overlay.ip_dict["status_gpio"]["phys_addr"], 0x1000)
    vdma = MMIO(overlay.ip_dict["vdma"]["phys_addr"], 0x1000)

    for _ in range(60):
        if (gpio.read(0) >> 5) & 1:
            break
        time.sleep(0.5)
    else:
        print("no receiver activity: is the source streaming?")
        return 2

    # One spare line: the scanout starts `skew` pixels in, so its last
    # line reads that far past the picture. Better to own those bytes
    # than to read whatever follows the buffer.
    fb = allocate(shape=(MODE_H + 1, MODE_W, 4), dtype="u1")
    fb[:] = 16
    fb.flush()

    # Read side: the raster scans the whole frame, forever.
    # The read engine's data lags its own start-of-frame marker by a
    # fixed number of beats -- proven by a self-test raster, which
    # paints from its own counters and lands pixel-perfect, while the
    # same design fed from memory is displaced. So start the read that
    # far in. The number is MEASURED per bitstream (ruler.py + capture
    # card); it goes away when scanout owns its own framebuffer reader.
    vdma.write(0x00, 0x3)
    for n in range(3):
        vdma.write(0x5C + 4 * n, fb.physical_address + args.skew * 4)
    vdma.write(0x58, MODE_W * 4)
    vdma.write(0x54, MODE_W * 4)
    vdma.write(0x50, MODE_H)

    # Write side: the ISP lands its window centred, forever.
    x0 = (MODE_W - ISP_W) // 2
    y0 = (MODE_H - ISP_H) // 2
    base = fb.physical_address + (y0 * MODE_W + x0) * 4
    vdma.write(0x30, 0x3)
    for n in range(3):
        vdma.write(0xAC + 4 * n, base)
    vdma.write(0xA8, MODE_W * 4)                # stride
    vdma.write(0xA4, ISP_W * 4)                 # hsize
    vdma.write(0xA0, ISP_H)                     # vsize -> go

    # Only now flip the stream into the armed S2MM, so the first frame
    # it ever sees starts at a tuser boundary.  Bit1 = consumer, bit0 =
    # broom; the broom sweeps while ISP mode is held.
    ctrl.write(0, 0x3)
    time.sleep(0.05)
    ctrl.write(0, 0x2)
    time.sleep(0.1)

    def report(tag):
        s1 = gpio.read(0)
        s2 = gpio.read(0x8)
        hdr = s1 >> 18
        # scanout's status word: sof-per-frame[2:0], locked, armed,
        # underflow, misalign, refused. Exactly one start-of-frame beat
        # per frame is correct; anything else means the stream's framing
        # is not what the raster is anchoring to.
        sc = (s2 >> 17) & 0x7FFF
        print(f"{tag}: lock={s1 & 1} ovf={(s1 >> 1) & 1} "
              f"refused={hdr & 1} bits={(hdr >> 4) & 0x1F} | scanout "
              f"armed={(sc >> 4) & 1} under={(sc >> 5) & 1} "
              f"misalign={(sc >> 6) & 1} win_refused={(sc >> 7) & 1} "
              f"sof/frame={sc & 7} | "
              f"s2mm_sr={vdma.read(0x34):#x} mm2s_sr={vdma.read(0x04):#x}")

    report("up")
    t0 = time.time()
    try:
        while args.seconds <= 0 or time.time() - t0 < args.seconds:
            time.sleep(10)
            report(f"t+{time.time() - t0:4.0f}s")
    except KeyboardInterrupt:
        pass
    finally:
        # The process's exit frees the CMA framebuffer, so the WRITER
        # must not outlive it: an S2MM left running scribbles 60 frames
        # a second over whatever the kernel hands those pages to next --
        # page cache included, which is how an SD card's rootfs rots.
        # The read side may keep scanning out; reads hurt nobody.
        vdma.write(0x30, 0x0)
        time.sleep(0.05)
    return 0


if __name__ == "__main__":
    sys.exit(main())
