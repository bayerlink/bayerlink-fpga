"""The fabric ISP demo: camera to colour, no ARM in the datapath.

blacklevel -> whitebalance -> bilinear demosaic -> rgb_gamma, all
generated by revela/np2hw and running in fabric between the bayerlink
receiver and the framebuffer. The ARM's whole job is this script:
point two VDMA channels at one buffer, flip the mode bit, report.

    python3 isp.py --bit rx.bit
"""
import argparse
import signal
import sys
import json
import time
from pathlib import Path

from pynq import Overlay, allocate, MMIO

MODE_W, MODE_H = 1920, 1080
ISP_W, ISP_H = 1920, 1080   # the TV's best defines the sensor's ask


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--bit", default="rx.bit")
    parser.add_argument("--interval", type=float, default=10.0,
                        help="heartbeat seconds; changes print immediately "
                             "regardless, so a swap is never missed")
    parser.add_argument("--output", choices=("direct", "grab", "both", "off"),
                        default="direct",
                        help="which tee branches run: the genlocked "
                             "direct-to-glass picture, the memory grabber, "
                             "both, or neither (standby -- the pipeline "
                             "keeps running and discards). The display "
                             "never depends on the grabber; grabbing is "
                             "an instrument for software to read")
    parser.add_argument("--seconds", type=float, default=0.0,
                        help="status loop duration; 0 = forever")
    args = parser.parse_args()

    # A plain kill (SIGTERM) must end the loop cleanly: the fabric keeps
    # the picture, and nothing is left needing kill -9.
    signal.signal(signal.SIGTERM, lambda *_: sys.exit(0))

    overlay = Overlay(args.bit, download=True)
    ctrl = MMIO(overlay.ip_dict["ctrl_gpio"]["phys_addr"], 0x1000)
    gpio = MMIO(overlay.ip_dict["status_gpio"]["phys_addr"], 0x1000)
    vdma = MMIO(overlay.ip_dict["vdma"]["phys_addr"], 0x1000)

    # Receiver activity = a header has been ACCEPTED (hdr_valid, bit
    # 27). This used to read a probe bit whose slot the island's
    # status bits now occupy -- and for one build it silently waited
    # on "ISP producing", which is exactly the bit that a held island
    # never raises. A start gate must watch the INPUT side.
    #
    # And it WAITS. The hardware self-heals from any order -- booted
    # with no cable, it parks and comes up the moment a source appears
    # (measured 2026-08-18: lock=0/rst=1 to frames flowing on plug-in,
    # no software touch). A tool that gave up after 30 seconds was the
    # only piece that did not, so "start the board, then plug the
    # camera" only worked if you were quick. The wait is bounded by
    # --seconds like every other wait in this script; it just is not
    # bounded by impatience.
    waited = time.time()
    while not (gpio.read(0) >> 27) & 1:
        if 0 < args.seconds <= time.time() - waited:
            print("no receiver activity within the run's own budget")
            return 2
        if (time.time() - waited) % 30 < 0.5:
            print(f"waiting for a source... ({time.time() - waited:.0f}s, "
                  "plug the camera whenever)")
        time.sleep(0.5)

    # The GRABBER's buffers. The display never reads these -- it is
    # direct -- so their layout serves software alone. Three frames,
    # circular, plus a guard row: with three, software reading the
    # buffer one behind the write pointer never races the writer,
    # which is a convenience the fabric provides for free. Whatever
    # fancier buffering a consumer wants is the consumer's to build.
    # (Grabbed frames land at a per-link-lock pixel offset -- the
    # write engine's known roll; a reader compensates when it cares.)
    FSIZE = MODE_H * MODE_W * 4
    fb = allocate(shape=(3 * MODE_H + 1, MODE_W, 4), dtype="u1")
    fb[:] = 16
    fb.flush()

    # The grabber lands the ISP window centred in a display-shaped
    # frame, so a grabbed buffer is pixel-for-pixel what direct puts
    # on glass.
    x0 = (MODE_W - ISP_W) // 2
    y0 = (MODE_H - ISP_H) // 2
    base = fb.physical_address + (y0 * MODE_W + x0) * 4
    vdma.write(0x30, 0x3 | (1 << 3) | (1 << 7))
    for n in range(3):
        vdma.write(0xAC + 4 * n, base + n * FSIZE)
    vdma.write(0xA8, MODE_W * 4)                # stride
    vdma.write(0xA4, ISP_W * 4)                 # hsize
    vdma.write(0xA0, ISP_H)                     # vsize -> go

    # Only now flip the stream into the armed S2MM, so the first frame
    # it ever sees starts at a tuser boundary.  Bit1 = consumer, bit0 =
    # broom; the broom sweeps while ISP mode is held.
    # Base control word: consumer select (bit1) plus the tee enables --
    # grab (bit3) and direct (bit4). The tee honours changes at frame
    # boundaries only, so these flip whole frames, never mid-frame.
    tee_bits = {"grab": 0x8, "direct": 0x10, "both": 0x18, "off": 0x0}
    cbase = 0x2 | tee_bits[args.output]
    ctrl.write(0, cbase | 1)
    time.sleep(0.05)
    ctrl.write(0, cbase)
    # ADDRESS FIRST, THEN ENABLE, and not the other way round: those 32
    # bits cross into the display clock without a synchroniser because
    # they are still by the time they matter, and enable rising is what
    # says they are. Bit 2 alongside the consumer select.
    time.sleep(0.1)

    hgpio = MMIO(overlay.ip_dict["hdr_gpio"]["phys_addr"], 0x1000)

    # A CONTROL build boots NEUTRAL -- gains 1.0, identity matrix --
    # which on this sensor is a green picture with no red. That is
    # correct hardware behaviour and wrong bench behaviour: real
    # software loads the calibration, so this does. Both files sit
    # beside this script; the map answers where, the defaults what.
    # ("red is absent" -- 2026-08-18, and it was wb.gain_0_0 at 256
    # where the calibration wanted 412.)
    map_p = Path(__file__).parent / "revela_isp.regmap.json"
    def_p = Path(__file__).parent / "revela_isp.defaults.json"
    if "isp" in overlay.ip_dict and map_p.exists() and def_p.exists():
        rmap = json.loads(map_p.read_text())
        base = overlay.ip_dict["isp"]["phys_addr"]
        csr = MMIO(base, 1 << rmap["control"]["address_bits"])
        addr = {f"{b['path']}.{r['name']}": (r["address"], r["bits"])
                for b in rmap["blocks"] for r in b["registers"]}
        for key, val in json.loads(def_p.read_text()).items():
            if key in addr:
                a, bits = addr[key]
                csr.write(a, (val + (1 << bits)) % (1 << bits))
        csr.write(addr["pipe.commit"][0], 1)
        deadline = time.time() + 1.0
        while (csr.read(addr["pipe.commit"][0]) & 1) and time.time() < deadline:
            time.sleep(0.005)
        state = "applied" if not (csr.read(addr["pipe.commit"][0]) & 1) \
            else "PENDING (no frames yet; lands at the first boundary)"
        print(f"calibration: {state}")

    def identity():
        """(source, resyncs, link up, drops) -- the one word a swap moves."""
        w = hgpio.read(0x8)
        return (w & 0xFF, (w >> 8) & 0xFF, (w >> 16) & 1, (w >> 17) & 0xFF)

    def report(tag):
        s1 = gpio.read(0)
        s2 = gpio.read(0x8)
        # The stream's identity and the link's health, one word:
        # {loss[7:0], up, resyncs[7:0], source[7:0]}. Counts, not flags,
        # so a poll that misses an event still sees that it happened.
        seq = hgpio.read(0)
        idw = hgpio.read(0x8)
        src, resyncs = idw & 0xFF, (idw >> 8) & 0xFF
        up, losses = (idw >> 16) & 1, (idw >> 17) & 0xFF
        hdr = s1 >> 18
        # scanout's status word: sof-per-frame[2:0], locked, armed,
        # underflow, misalign, refused -- and on a genlocked raster,
        # glocked at bit 14: frame starts passing at the window origin,
        # four in a row. Exactly one start-of-frame beat per frame is
        # correct; anything else means the stream's framing is not what
        # the raster is anchoring to.
        sc = (s2 >> 17) & 0x7FFF
        # The island's six levels -- see isl_cat in bd.tcl.
        isl = (s1 >> 2) & 0x3F
        print(f"{tag}: lock={s1 & 1} ovf={(s1 >> 1) & 1} "
              f"isl[rst={isl & 1} inV={(isl >> 1) & 1} inR={(isl >> 2) & 1} "
              f"outV={(isl >> 3) & 1} shV={(isl >> 4) & 1} "
              f"shR={(isl >> 5) & 1}] "
              f"refused={hdr & 1} bits={(hdr >> 4) & 0x1F} | scanout "
              f"armed={(sc >> 4) & 1} under={(sc >> 5) & 1} "
              f"misalign={(sc >> 6) & 1} win_refused={(sc >> 7) & 1} "
              f"sof/frame={sc & 7} glocked={(sc >> 14) & 1} | "
              f"s2mm_sr={vdma.read(0x34):#x} | "
              f"src={src} frame={seq} link={'up' if up else 'DOWN'} "
              f"drops={losses} resyncs={resyncs}")

    report("up")
    t0 = time.time()
    # Poll the identity word FAST and print when it moves. A hot swap is
    # over in well under a second: on a ten-second heartbeat the unplug,
    # the recovery and the new sensor all land in one line, which is the
    # same as not seeing them.
    last = identity()
    beat = t0
    unhalts, unhalt_t = 0, 0.0
    try:
        while args.seconds <= 0 or time.time() - t0 < args.seconds:
            time.sleep(0.05)
            now = identity()
            if now != last:
                src, res, up, drops = now
                report(f"t+{time.time() - t0:4.0f}s CHANGE "
                       f"link={'up' if up else 'DOWN'} src={src} "
                       f"drops={drops} resyncs={res}")
                last = now
            if time.time() - beat >= args.interval:
                beat = time.time()
                report(f"t+{time.time() - t0:4.0f}s")
            # SUPERVISOR, and labelled a patch: a VDMA that halts on a
            # framing hiccup (SOFLateErr at a mid-frame unplug) never
            # restarts itself, so the link would heal and the picture
            # would stay frozen forever. The real fix retires the
            # engine outright; until then a halted writer is cleared
            # and re-armed -- only while the link is up, at most once a
            # second, and COUNTED, because a restart happening often
            # enough to matter is a bug report, not a recovery.
            if (time.time() - unhalt_t > 1.0
                    and now[2] and args.output in ("grab", "both")):
                sr = vdma.read(0x34)
                if sr & 1:                             # Halted
                    vdma.write(0x34, sr)               # W1C the stickies
                    vdma.write(0x30, 0x3)              # run, circular
                    vdma.write(0xA8, MODE_W * 4)
                    vdma.write(0xA4, ISP_W * 4)
                    vdma.write(0xA0, ISP_H)            # vsize -> go
                    unhalts += 1
                    unhalt_t = time.time()
                    report(f"t+{time.time() - t0:4.0f}s UNHALT #{unhalts} "
                           f"(s2mm was 0x{sr:08x})")
    except KeyboardInterrupt:
        pass
    finally:
        # The process's exit frees the CMA buffers, so the GRABBER
        # must not outlive it: an S2MM left running scribbles frames
        # over whatever the kernel hands those pages to next -- page
        # cache included, which is how an SD card's rootfs rots. The
        # display is direct and keeps the picture; it never touched
        # this memory.
        vdma.write(0x30, 0x0)
        time.sleep(0.05)
    return 0


if __name__ == "__main__":
    sys.exit(main())
