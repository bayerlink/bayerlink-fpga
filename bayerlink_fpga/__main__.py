"""Generate the receiver, behind one front end, into a build directory.

    python3 -m bayerlink_fpga bayerlink_fpga.frontends.dvi2rgb \\
        --out <build dir> --fifo-depth 256 --max-line-bytes 4096 \\
        --bits 12 --link-mode 1080p30

The front end's facts -- the byte-lane map -- shape the receiver. How the
front end is built into a design, configured and pinned, is the board's,
in its own block library; this never sees it.

Writes <build dir>/hdl/bayerlink_rx.v, ddc_slave.v and edid.bin, and
<build dir>/generated/receiver.tcl, which the synthesis run sources for
what the front end's vendor IP expects beside it. The receiver's Verilog
is described, file by file, in bayerlink_fpga/modules.json.
"""
import argparse
import sys
from pathlib import Path

from bayerlink_fpga import ddc, frontends, receiver


def main() -> int:
    parser = argparse.ArgumentParser(prog="python3 -m bayerlink_fpga")
    parser.add_argument("frontend",
                        help="the front end, bayerlink_fpga.frontends.<name>")
    parser.add_argument("--out", required=True, type=Path,
                        help="the build directory")
    parser.add_argument("--max-line-bytes", type=int, required=True)
    parser.add_argument("--fifo-depth", type=int, required=True)
    # The depth samples LEAVE at, and the ONLY depth that is a build
    # fact. What the sensor SENT is the header's, run-time, any of
    # 8/10/12/14/16 -- so a different sensor can be plugged in without
    # rebuilding, and the receiver scales it to this on the way out.
    #
    # REQUIRED, with no default. The number has one owner, the design
    # the samples feed, and its build passes it here and to its own
    # block design from that one place. A default here would be a
    # second owner that agrees until the day it quietly does not.
    parser.add_argument("--bits", type=int, required=True,
                        help="the depth samples leave at, which the design "
                             "consuming them owns; never defaulted here")
    parser.add_argument("--link-mode", required=True,
                        help="the raster the EDID advertises")
    args = parser.parse_args()

    fe = frontends.load(args.frontend)
    hdl = args.out / "hdl"
    print("generated " + receiver.generate(
        hdl, lane_map=fe["lane_map"],
        vsync_active_high=fe["vsync_active_high"],
        fifo_depth=args.fifo_depth, max_line_bytes=args.max_line_bytes,
        bits=args.bits))
    print("generated " + ddc.generate(hdl, args.link_mode))

    name = fe["name"]
    tcl = [
        "# GENERATED by bayerlink_fpga -- do not edit.",
        "#",
        f"# The {name} front end's needs at synthesis, under the name every",
        "# run calls whichever front end this is.",
        f"source {{{fe['tcl']}}}",
        "# Whatever the front end's vendor IP expects beside a batch run.",
        "proc bayerlink_frontend_synth_prep {ip_repo} {",
        f"    {name}_synth_prep $ip_repo",
        "}",
        "",
    ]
    gen = args.out / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "receiver.tcl").write_text("\n".join(tcl))
    print(f"generated {gen / 'receiver.tcl'} ({name} front end)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
